"""Run every experiment and write results/RESULTS.md plus one CSV per table.

Usage:  python -m experiments.run_all
"""
import time

import numpy
import scipy

from . import (exp1_routing_savings, exp2_staged_selection, exp3_multifidelity, exp4_confidence,
               exp5_named_sequences, exp6_third_stage_value, exp7_workload_profiles)
from .common import BASE_SEED, RESULTS


def main() -> None:
    sections = []
    for module in (exp1_routing_savings, exp2_staged_selection, exp3_multifidelity, exp4_confidence,
                   exp5_named_sequences, exp6_third_stage_value, exp7_workload_profiles):
        start = time.time()
        sections.append(module.run())
        print(f"{module.__name__}: {time.time() - start:.0f}s")
    header = ("# Results\n\n"
              "All figures come from simulations on synthetic data. No real model was run.\n"
              f"Generated by `python -m experiments.run_all` with base seed {BASE_SEED}, "
              f"numpy {numpy.__version__}, scipy {scipy.__version__}. "
              "The same command reproduces every number.\n")
    (RESULTS / "RESULTS.md").write_text(header + "\n" + "\n".join(sections))
    print("written", RESULTS / "RESULTS.md")


if __name__ == "__main__":
    main()

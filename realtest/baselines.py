"""Step 3 of the real-model test: how far does the labelled history go without a language model?

Two questions, answered from the same split and the same stored model outputs as analyze.py:

1. A classical classifier trained on the history (TF-IDF over words and word pairs, logistic
   regression): how accurate is it, with all the labelled history and with only a few
   labelled examples per category?
2. With few labelled examples, does a language model help? The hybrid lets the classifier
   answer when it is confident and sends the rest to the language model. Its confidence
   threshold is chosen on the calibration half; accuracy and cost are measured on the test half.

No language model runs here: their answers are read from realtest/outputs/.

Usage:
    python -m realtest.baselines --task departments
"""
from __future__ import annotations

import argparse
import csv
import pathlib
import time

import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression

from . import data
from .analyze import BOOTSTRAP, interval, load_outputs, table
from .run_models import DEFAULT_SHOTS

HERE = pathlib.Path(__file__).resolve().parent
PER_CATEGORY = (1, 2, 4, 8, 16, 32, 64, 128, None)      # None = all the labelled history
DRAWS = 5                                              # random draws of the labelled examples per size


def classifier(texts, labels):
    vectorizer = TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True)
    model = LogisticRegression(max_iter=3000, C=10.0).fit(vectorizer.fit_transform(texts), labels)
    return vectorizer, model


def sample(train, per_category, rng):
    if per_category is None:
        return train
    by_label = {}
    for i, (_, label) in enumerate(train):
        by_label.setdefault(label, []).append(i)
    keep = [i for items in by_label.values() for i in rng.choice(items, min(per_category, len(items)), replace=False)]
    return [train[i] for i in sorted(keep)]


def hybrid(prob_max, clf_correct, llm_correct, calibration, grid=np.round(np.arange(0.0, 1.0001, 0.02), 2)):
    """Classifier answers when its top probability is at least t, otherwise the language model.
    t is the one that maximises accuracy on the calibration half."""
    best = max(grid, key=lambda t: (np.where(prob_max >= t, clf_correct, llm_correct)[calibration].mean(), -t))
    return best, np.where(prob_max >= best, clf_correct, llm_correct), prob_max < best


def run(task_name="departments", shots=DEFAULT_SHOTS, seed=data.SEED) -> str:
    task = data.load(task_name)
    outputs = load_outputs(task, shots)
    common = set.intersection(*(set(rows) for rows in outputs.values()))
    order = [int(i) for i in data.select(len(task.test), None) if int(i) in common]     # as in analyze.py
    test_texts = [task.test[i][0] for i in order]
    labels = np.array([task.test[i][1] for i in order])
    calibration = data.split(len(order), seed)
    held_out = ~calibration
    models = sorted(outputs, key=lambda m: np.mean([outputs[m][i]["compute_seconds"] for i in order]))
    llm_correct = {m: np.array([outputs[m][i]["correct"] for i in order]) for m in models}
    llm_seconds = {m: np.mean([outputs[m][i]["compute_seconds"] for i in order]) for m in models}
    large = models[-1]
    rng = np.random.default_rng([seed, 3])
    resamples = rng.integers(0, int(held_out.sum()), size=(BOOTSTRAP, int(held_out.sum())))

    def ci(values):
        v = values[held_out]
        lo, hi = interval(v[resamples].mean(axis=1))
        return v.mean(), lo, hi

    lines = ["# Real-model test: the history without a language model", "",
             f"Workload: {task.title}. Same split as REPORT_{task_name}.md: thresholds on the calibration half "
             f"({int(calibration.sum())} requests), every figure on the test half ({int(held_out.sum())} requests), "
             "95% bootstrap intervals.", "",
             "The classifier is TF-IDF over words and word pairs with logistic regression, trained on labelled past "
             "requests. The language models answer with no examples, as in the main report.", "",
             f"This file is generated by `python -m realtest.baselines --task {task_name}`.", ""]

    # 1. all the history
    vec, model = classifier([t for t, _ in task.train], [y for _, y in task.train])
    tick = time.perf_counter()
    predicted = model.predict(vec.transform(test_texts))
    ms = (time.perf_counter() - tick) / len(test_texts) * 1000
    full = predicted == labels
    acc, lo, hi = ci(full)
    lines += ["## With all the labelled history", "",
              table(["Approach", "Right answers", "Compute per request"],
                    [[f"Classifier on {len(task.train):,} labelled requests", f"{acc:.1%} ({lo:.1%} to {hi:.1%})", f"{ms:.3f} ms"]]
                    + [[f"{m} alone, no examples", "{:.1%} ({:.1%} to {:.1%})".format(*ci(llm_correct[m])),
                        f"{llm_seconds[m] * 1000:.0f} ms"] for m in models]), "",
              "Accuracy is on the test half. Compute for the classifier is a batched prediction over all requests "
              "on a different machine; for the models it is the mean over all requests, one at a time, on the office PC "
              "of the main run. Only the order of magnitude compares.", ""]

    # 2. few labelled examples per category
    rows, curve = [], []
    for k in PER_CATEGORY:
        draws = 1 if k is None else DRAWS
        alone, mixed, sent, per_request = [], [], [], []
        for _ in range(draws):
            train = sample(task.train, k, rng)
            vec, model = classifier([t for t, _ in train], [y for _, y in train])
            proba = model.predict_proba(vec.transform(test_texts))
            pred = model.classes_[proba.argmax(axis=1)]
            correct = pred == labels
            _, combined, to_llm = hybrid(proba.max(axis=1), correct, llm_correct[large], calibration)
            alone.append(correct[held_out].mean())
            mixed.append(combined[held_out].mean())
            sent.append(to_llm[held_out].mean())
            per_request.append(combined.astype(float))
        # paired bootstrap of the hybrid against the language model alone, on the request-level mean over draws
        gain, gain_lo, gain_hi = ci(np.mean(per_request, axis=0) - llm_correct[large])
        size = "all" if k is None else str(k)
        curve.append({"per_category": size, "labelled": len(train), "classifier": round(float(np.mean(alone)), 4),
                      "classifier_min": round(float(np.min(alone)), 4), "classifier_max": round(float(np.max(alone)), 4),
                      "hybrid": round(float(np.mean(mixed)), 4),
                      "hybrid_gain": round(float(gain), 4), "hybrid_gain_lo": round(float(gain_lo), 4),
                      "hybrid_gain_hi": round(float(gain_hi), 4), "share_to_llm": round(float(np.mean(sent)), 4),
                      "llm_alone": round(float(llm_correct[large][held_out].mean()), 4), "llm": large})
        rows.append([size, f"{len(train):,}", f"{np.mean(alone):.1%}", f"{np.mean(mixed):.1%}",
                     f"{gain * 100:+.1f} ({gain_lo * 100:+.1f} to {gain_hi * 100:+.1f})", f"{np.mean(sent):.0%}"])
    lines += ["## With few labelled examples", "",
              f"For each size, labelled examples are drawn at random from the history ({DRAWS} draws, mean shown). "
              f"The hybrid sends to {large} the requests on which the classifier is not confident enough; the "
              "threshold on its top class probability (uncalibrated, grid of 0.02) is the one with the highest "
              "accuracy on the calibration half; cost is not part of the choice. Its compute, against "
              f"{large} alone, is roughly the share it sends. The difference is a paired bootstrap interval on the "
              "test half, with each request's outcome averaged over the draws.", "",
              table(["Labelled examples per category", "Labelled requests", "Classifier alone",
                     f"Classifier, then {large}", f"Difference from {large} alone, points", f"Share sent to {large}"], rows), "",
              f"For reference, {large} alone: {llm_correct[large][held_out].mean():.1%}.", ""]

    lines += ["## Limits", "",
              "- One task with 10 broad categories and many labelled examples: an easy case for a classifier.",
              "- The classifier is not tuned beyond sublinear TF and C = 10; the language models are not tuned either "
              "(one zero-shot prompt, default quantization).",
              "- New categories, or categories with no labelled history, are not tested here: that is where a "
              "language model that reads the category names should matter most.", ""]
    with open(HERE.parent / "results" / f"realtest_{task_name}_history_curve.csv", "w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(curve[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(curve)
    report = "\n".join(lines)
    (HERE / f"BASELINES_{task_name}.md").write_text(report, encoding="utf-8")
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--task", choices=sorted(data.SOURCES), default="departments")
    parser.add_argument("--shots", type=int, default=0, help="prompt variant of the stored model outputs (default 0)")
    args = parser.parse_args()
    print(run(args.task, args.shots))


if __name__ == "__main__":
    main()
